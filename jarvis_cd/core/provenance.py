"""Run provenance: ``jarvis.provenance.v1``.

Written by the run itself (not by a caller) into
``<execution>/provenance.json`` and listed as a core ``provenance``
artifact, so a consumer can check what an execution really used:

* the Spack selection, the resolved hashes and the ``spack.lock`` digest
  (from the run's install record);
* per MPI launch: ``readlink -f`` of the launcher and of the binary, the
  binary's ``ldd``, each node's hostname with its rank count and one rank's
  ``/proc/<pid>/maps``;
* the job environment (secret-looking names redacted).

MPI launches (``jarvis_cd.shell.mpi_exec``) call :func:`capture_launch`
when ``JARVIS_PROVENANCE_DIR`` is set (the pipeline sets it for every
package of an execution). It writes ``launch-<n>.json`` and prefixes each
rank command with a small ``/bin/sh`` wrapper that records
``ranks/<host>-<rank>.txt`` and, for the first rank to claim it, samples
``/proc/<pid>/maps`` of the exec'ed program. ``JARVIS_PROVENANCE=off``
disables both. :func:`write_provenance` assembles the record at the end of
``Pipeline.run``.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping, Optional

PROVENANCE_SCHEMA = "jarvis.provenance.v1"
PROVENANCE_FILE = "provenance.json"
PROVENANCE_DIR_ENV = "JARVIS_PROVENANCE_DIR"
PROVENANCE_SWITCH_ENV = "JARVIS_PROVENANCE"

_SECRET_NAME = re.compile(
    r"(TOKEN|SECRET|PASSWORD|PASSWD|CREDENTIAL|PRIVATE_KEY|API_KEY|ACCESS_KEY|"
    r"SESSION_KEY|COOKIE)",
    re.IGNORECASE,
)
_MAX_MAPS_BYTES = 4 * 1024 * 1024

#: Rank wrapper: ``sh rank-wrapper.sh <launch dir> <command...>``. The maps
#: sampler is double-forked so it is never a child of the program, and it
#: only keeps a sample once ``/proc/<pid>/exe`` is no longer the shell
#: itself, i.e. after ``exec``. Samples repeat for up to ~10 s so late
#: shared-library loads are included; the last one wins.
RANK_WRAPPER = r"""#!/bin/sh
# Generated by jarvis (provenance rank wrapper); see jarvis_cd/core/provenance.py
d="$1"; shift
r="${OMPI_COMM_WORLD_RANK:-${PMIX_RANK:-${PMI_RANK:-${SLURM_PROCID:-x}}}}"
h="$(hostname 2>/dev/null || uname -n)"
p=$$
mkdir -p "$d/ranks" 2>/dev/null
printf '%s %s %s\n' "$h" "$r" "$p" > "$d/ranks/$h-$r-$p.txt" 2>/dev/null
if mkdir "$d/maps.claim" 2>/dev/null; then
  printf '%s %s %s\n' "$h" "$r" "$p" > "$d/maps.claim/owner" 2>/dev/null
  self="$(readlink "/proc/$p/exe" 2>/dev/null)"
  ( ( n=0
      while [ "$n" -lt 40 ] && [ -r "/proc/$p/maps" ]; do
        e="$(readlink "/proc/$p/exe" 2>/dev/null)"
        if [ -n "$e" ] && [ "$e" != "$self" ]; then
          cat "/proc/$p/maps" > "$d/maps.tmp" 2>/dev/null \
            && printf '%s\n' "$e" > "$d/maps.exe" \
            && mv -f "$d/maps.tmp" "$d/maps.txt"
        fi
        n=$((n + 1)); sleep 0.25
      done ) </dev/null >/dev/null 2>&1 & ) </dev/null >/dev/null 2>&1
fi
exec "$@"
"""


def _utc_now() -> str:
    return _dt.datetime.now(_dt.timezone.utc).isoformat().replace("+00:00", "Z")


def provenance_enabled(env: Optional[Mapping[str, str]] = None) -> bool:
    for source in (env or {}, os.environ):
        value = str(source.get(PROVENANCE_SWITCH_ENV, "")).strip().lower()
        if value:
            return value not in ("off", "0", "false", "no", "none")
    return True


def redact_environment(env: Mapping[str, str]) -> Dict[str, Any]:
    """``{"variables": {...}, "redacted": [names]}`` with secret values hidden."""
    variables: Dict[str, str] = {}
    redacted: List[str] = []
    for name in sorted(env):
        if _SECRET_NAME.search(name):
            variables[name] = "<redacted>"
            redacted.append(name)
        else:
            variables[name] = str(env[name])
    return {"variables": variables, "redacted": redacted}


def _which(program: str, env: Mapping[str, str], cwd: Optional[str]) -> Optional[str]:
    if "/" in program:
        path = Path(program)
        if not path.is_absolute() and cwd:
            path = Path(cwd) / path
        return str(path) if path.exists() else None
    return shutil.which(program, path=env.get("PATH") or os.environ.get("PATH"))


def _realpath(path: Optional[str]) -> Optional[str]:
    return os.path.realpath(path) if path else None


def command_program(command: str) -> Optional[str]:
    """The program a rank command runs (skipping ``env`` and ``VAR=value``)."""
    try:
        tokens = shlex.split(command)
    except ValueError:
        tokens = command.split()
    index = 0
    if tokens and os.path.basename(tokens[0]) == "env":
        index = 1
        while index < len(tokens) and (
            "=" in tokens[index] or tokens[index].startswith("-")
        ):
            index += 1
    while index < len(tokens) and re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", tokens[index]):
        index += 1
    return tokens[index] if index < len(tokens) else None


def _ldd(binary: str, env: Mapping[str, str]) -> Dict[str, Any]:
    run_env = dict(os.environ)
    for name in ("LD_LIBRARY_PATH", "PATH"):
        if env.get(name):
            run_env[name] = str(env[name])
    try:
        completed = subprocess.run(
            ["ldd", binary], capture_output=True, text=True, timeout=60,
            env=run_env, check=False,
        )
    except (OSError, subprocess.SubprocessError) as error:
        return {"returncode": None, "lines": [], "error": str(error)}
    return {
        "returncode": completed.returncode,
        "lines": completed.stdout.splitlines(),
        "error": completed.stderr.strip() or None,
    }


def _next_launch_dir(root: Path) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    for number in range(1, 100000):
        candidate = root / f"launch-{number:03d}"
        try:
            candidate.mkdir()
        except FileExistsError:
            continue
        return candidate
    raise RuntimeError("too many provenance launches")


def capture_launch(launch: Any, cwd: Optional[str] = None) -> None:
    """Record one MPI launch and wrap its rank command(s).

    ``launch`` is a ``LocalMpiExec`` before ``mpicmd()``: this reads its
    ``mpi_env``, ``mpi_cmd``, ``nprocs``, ``ppn``, ``hostfile`` and
    ``original_cmd``/``cmd_list`` and rewrites the command(s). Never raises:
    provenance must not break a run.
    """
    env = dict(getattr(launch, "mpi_env", None) or {})
    root = env.get(PROVENANCE_DIR_ENV) or os.environ.get(PROVENANCE_DIR_ENV)
    if not root or not provenance_enabled(env):
        return
    try:
        launch_dir = _next_launch_dir(Path(root))
        wrapper = Path(root) / "rank-wrapper.sh"
        if not wrapper.is_file():
            tmp = wrapper.with_name(f".{wrapper.name}.{os.getpid()}")
            tmp.write_text(RANK_WRAPPER, encoding="utf-8")
            os.replace(tmp, wrapper)
        launcher = (getattr(launch, "mpi_cmd", None) or "mpiexec").split()[0]
        launcher_path = _which(launcher, env, cwd)
        commands: List[str] = (
            [entry["cmd"] for entry in launch.cmd_list]
            if getattr(launch, "cmd_list", None)
            else [launch.original_cmd]
        )
        binaries = []
        for command in commands:
            program = command_program(command)
            found = _which(program, env, cwd) if program else None
            real = _realpath(found)
            binaries.append({
                "command": command,
                "program": program,
                "path": found,
                "realpath": real,
                "ldd": _ldd(real, env) if real else None,
            })
        hostfile = getattr(launch, "hostfile", None)
        network = getattr(launch, "network", None)
        launch_facts = (network or {}).get("site_facts") if isinstance(network, dict) else None
        from jarvis_cd.core.site_facts import launch_advisories

        document = {
            "schema_version": "jarvis.provenance-launch.v1",
            "launched_at": _utc_now(),
            "exec_type": type(launch).__name__,
            "launcher": launcher,
            "launcher_path": launcher_path,
            "launcher_realpath": _realpath(launcher_path),
            "mpi_prefix": getattr(launch, "mpi_prefix", None),
            "nprocs": getattr(launch, "nprocs", None),
            "ppn": getattr(launch, "ppn", None),
            "hosts": list(getattr(hostfile, "hosts", []) or []),
            "hostfile": getattr(hostfile, "path", None),
            "binaries": binaries,
            "network": network,
            # Non-blocking site-fact issues of this launch (including those
            # from a launch-time net collect), and the full report.
            "advisories": launch_advisories(launch_facts),
            "site_facts": launch_facts if isinstance(launch_facts, dict) else None,
            "placement": getattr(launch, "placement", None),
            "rank_env": redact_environment(env),
        }
        (launch_dir / "launch.json").write_text(
            json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        if isinstance(launch_facts, dict) and launch_facts.get("issues"):
            from jarvis_cd.core.site_facts import record_execution_site_facts

            # Into the execution record now, not only when the run ends.
            record_execution_site_facts(Path(root).parent,
                                        env.get("JARVIS_EXECUTION_ID")
                                        or os.environ.get("JARVIS_EXECUTION_ID"))
        prefix = f"/bin/sh {shlex.quote(str(wrapper))} {shlex.quote(str(launch_dir))} "
        if getattr(launch, "cmd_list", None):
            for entry in launch.cmd_list:
                entry["cmd"] = prefix + entry["cmd"]
        else:
            launch.original_cmd = prefix + launch.original_cmd
    except Exception as error:  # pragma: no cover - defensive
        print(f"jarvis provenance: launch not recorded: {error}", file=sys.stderr)


def _read_text(path: Path, limit: Optional[int] = None) -> Optional[str]:
    try:
        data = path.read_bytes()
    except OSError:
        return None
    if limit is not None and len(data) > limit:
        data = data[:limit]
    return data.decode("utf-8", errors="replace")


def _rank_files(launch_dir: Path) -> List[Dict[str, Any]]:
    ranks = []
    for path in sorted((launch_dir / "ranks").glob("*.txt")):
        parts = (_read_text(path) or "").split()
        if len(parts) >= 3:
            ranks.append({"hostname": parts[0], "rank": parts[1], "pid": parts[2]})
    return ranks


def _nodes(ranks: Iterable[Mapping[str, Any]]) -> List[Dict[str, Any]]:
    counts: Dict[str, int] = {}
    for rank in ranks:
        counts[rank["hostname"]] = counts.get(rank["hostname"], 0) + 1
    return [{"hostname": host, "ranks": counts[host]} for host in sorted(counts)]


def _launches(root: Path) -> List[Dict[str, Any]]:
    launches = []
    for launch_dir in sorted(root.glob("launch-*")):
        try:
            document = json.loads((launch_dir / "launch.json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        ranks = _rank_files(launch_dir)
        maps_text = _read_text(launch_dir / "maps.txt", _MAX_MAPS_BYTES)
        owner = (_read_text(launch_dir / "maps.claim" / "owner") or "").split()
        mapped_files = sorted({
            line.split(None, 5)[5].strip()
            for line in (maps_text or "").splitlines()
            if len(line.split(None, 5)) == 6 and line.split(None, 5)[5].startswith("/")
        })
        document.update({
            "id": launch_dir.name,
            "ranks": ranks,
            "nodes": _nodes(ranks),
            "maps": {
                "hostname": owner[0] if len(owner) > 0 else None,
                "rank": owner[1] if len(owner) > 1 else None,
                "pid": owner[2] if len(owner) > 2 else None,
                "exe": (_read_text(launch_dir / "maps.exe") or "").strip() or None,
                "captured": maps_text is not None,
                "text": maps_text,
                "files": mapped_files,
            },
        })
        launches.append(document)
    return launches


def _spack_section(record_path: Optional[Path]) -> Dict[str, Any]:
    if record_path is None:
        return {"install_record": None}
    try:
        record = json.loads(record_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"install_record": str(record_path), "error": "unreadable"}
    env = record.get("spack_env") or {}
    lock_path = env.get("lock")
    lock_sha256 = None
    if lock_path and Path(lock_path).is_file():
        lock_sha256 = hashlib.sha256(Path(lock_path).read_bytes()).hexdigest()
    packages = {}
    for name, entry in (record.get("packages") or {}).items():
        if not isinstance(entry, Mapping):
            continue
        packages[name] = {
            "status": entry.get("status"),
            "spec": entry.get("spec"),
            "root_hash": (entry.get("root") or {}).get("hash"),
            "lock_hash": entry.get("lock_hash"),
            "mpi": entry.get("mpi"),
        }
    from jarvis_cd.core.spack_install import (
        spack_config_scopes,
        spack_local_config_disabled,
    )

    load_scopes = [record["spack_scope"]] if record.get("spack_scope") else []
    return {
        "install_record": str(record_path),
        "spack_root": record.get("spack_root"),
        "spack_executable": record.get("spack_executable"),
        # What the run's `spack load` read, resolved now in the run's env.
        "local_config_disabled": spack_local_config_disabled(),
        "config_scopes": spack_config_scopes(load_scopes),
        # What the install's spec/find/concretize read, as it recorded them.
        "install_config_scopes": record.get("spack_config_scopes") or [],
        "spack_repos": record.get("spack_repos") or [],
        "site_prep": record.get("spack_site_prep"),
        "env_dir": env.get("dir"),
        "lock": lock_path,
        "lock_sha256": lock_sha256,
        "lock_sha256_recorded": env.get("lock_sha256"),
        "roots": env.get("roots") or [],
        "packages": packages,
    }


def _jarvis_section() -> Dict[str, Any]:
    try:
        from importlib.metadata import version

        jarvis_version: Optional[str] = version("jarvis_cd")
    except Exception:
        jarvis_version = None
    command = shutil.which("jarvis")
    if command is None:
        # A venv or pipx install called by path has its bin dir off PATH.
        sibling = Path(os.path.abspath(sys.executable)).parent / "jarvis"
        command = str(sibling) if sibling.is_file() else None
    return {
        "version": jarvis_version,
        "package": os.path.realpath(str(Path(__file__).resolve().parents[1])),
        "python": os.path.realpath(sys.executable),
        "command": command,
        "command_realpath": _realpath(command),
    }


def write_provenance(
    execution_root: Path,
    *,
    execution_id: str,
    pipeline_id: Optional[str],
    install_records: Iterable[Path] = (),
    job_env: Optional[Mapping[str, str]] = None,
    phase_timings: Optional[Mapping[str, Any]] = None,
) -> Path:
    """Assemble ``<execution>/provenance.json`` from the launch captures."""
    execution_root = Path(execution_root)
    record_path = next((Path(p) for p in install_records if Path(p).is_file()), None)
    launches = _launches(execution_root / "provenance")
    all_ranks = [rank for launch in launches for rank in launch["ranks"]]
    mpiexec = sorted({
        launch["launcher_realpath"] for launch in launches if launch.get("launcher_realpath")
    })
    document = {
        "schema_version": PROVENANCE_SCHEMA,
        "execution_id": execution_id,
        "pipeline_id": pipeline_id,
        "written_at": _utc_now(),
        "host": os.uname().nodename if hasattr(os, "uname") else None,
        "scheduler_job": {
            name: os.environ[name]
            for name in ("SLURM_JOB_ID", "SLURM_JOB_NODELIST", "PBS_JOBID",
                         "LSB_JOBID", "FLUX_JOB_ID")
            if os.environ.get(name)
        },
        "jarvis": _jarvis_section(),
        "spack": _spack_section(record_path),
        "mpiexec_realpaths": mpiexec,
        "binaries": sorted({
            binary["realpath"]
            for launch in launches for binary in launch["binaries"] if binary.get("realpath")
        }),
        "nodes": _nodes(all_ranks),
        # The data/control networks each launch used and where they came
        # from (resource graph selection or a person's override).
        "mpi_network": [
            {"launch": launch["id"], **launch["network"]}
            for launch in launches
            if isinstance(launch.get("network"), dict)
        ],
        # Ranks per node each launch used and why (task geometry, physical
        # cores, or the package's ppn); see jarvis_cd.util.placement.
        "mpi_placement": [
            {"launch": launch["id"], **launch["placement"]}
            for launch in launches
            if isinstance(launch.get("placement"), dict)
        ],
        "launches": launches,
        # Where the run's time went before and during its steps: env
        # activation (captured env or spack load), configure, each
        # package's start and ready, the first step (jarvis.phase-timings.v1).
        "phase_timings": dict(phase_timings) if phase_timings else None,
        "job_env": redact_environment(job_env if job_env is not None else os.environ),
    }
    path = execution_root / PROVENANCE_FILE
    tmp = path.with_name(f".{path.name}.{os.getpid()}")
    tmp.write_text(json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, path)
    return path
